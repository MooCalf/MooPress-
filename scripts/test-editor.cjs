const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs/promises');

app.setPath('userData', path.join(app.getPath('temp'), 'moopress-integration'));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1280, height: 1000, webPreferences: { preload: path.join(__dirname, 'test-preload.cjs'), contextIsolation: true, offscreen: true, backgroundThrottling: false } });
  win.webContents.on('console-message', (event) => { if (event.level === 'error') console.error(event.message); });
  try {
    await win.loadURL(process.env.MOOPRESS_TEST_URL || 'http://localhost:5173');
    const result = await win.webContents.executeJavaScript(`(async () => {
      const { app, emit } = await import('/src/app.js');
      const { loadProject } = await import('/src/fileops.js');
      const { createProject, newChapter } = await import('/src/project.js');
      const { openView, syncChapters, chapterState, setChapterState } = await import('/src/editor.js');
      const { updateLayout } = await import('/src/layout.js');
      const { insertPicture } = await import('/src/insert.js');
      const { buildBookHTML } = await import('/src/exporter.js');
      const { exportPayload } = await import('/src/formats/index.js');
      const { normalizeProject } = await import('/src/project.js');
      const { elementDialog, footnoteDialog, watermarkDialog, tableOptionsDialog, refreshPageElements } = await import('/src/pageElements.js');
      const { addChapter, moveChapter } = await import('/src/sidebar.js');
      const { closeRadial } = await import('/src/features/radialMenu.js');
      const wait = () => new Promise(resolve => setTimeout(resolve, 190));
      const applyDialog = () => document.querySelector('.modal-overlay:last-child .dialog-footer .primary').click();
      const checks = [];
      const check = (name, condition) => checks.push({ name, pass: !!condition });
      const p = createProject(); p.title = 'Test <Book>'; p.chapters.push(newChapter('Second chapter'));
      loadProject(p, null);
      check('title page opens by default', app.view === 'title' && !document.getElementById('title-page').hidden);
      check('all chapters visible below the title', document.querySelectorAll('.chapter-paper').length === 2 && [...document.querySelectorAll('.chapter-paper')].every(el => !el.hidden));
      await insertPicture();
      check('title artwork is stored', app.project.titleImages?.length === 1);
      check('title artwork exports', buildBookHTML().includes('<img src="data:image/svg+xml;base64'));
      document.querySelector('.title-art-button').click();
      document.querySelector('.modal-overlay input[type=number]').value = 45;
      document.querySelector('.modal-overlay input:not([type])').value = 'Cover <art>';
      applyDialog(); await wait();
      check('title picture options persist', app.project.titleImages[0].width === 45 && app.project.titleImages[0].alt === 'Cover <art>');
      check('title picture width follows page content', Math.abs(document.querySelector('.title-art').getBoundingClientRect().width / document.querySelector('.tp-inner').getBoundingClientRect().width - 0.45) < 0.01);
      openView(p.chapters[0].id); app.editor.commands.setContent('<p>First chapter edits</p>');
      openView(p.chapters[1].id); app.editor.commands.setContent('<p>Second chapter edits</p>');
      syncChapters();
      check('navigation preserves both chapters', JSON.stringify(app.project.chapters[0].content).includes('First chapter edits') && JSON.stringify(app.project.chapters[1].content).includes('Second chapter edits'));
      updateLayout({ pageNumbers: { show: true, position: 'footer-center', format: 'n-of' } });
      check('preview page totals span the book', document.querySelectorAll('.hf-footer')[1].textContent.includes('Page 3 of 3'));
      const shortState = chapterState(p.chapters[0].id);
      setChapterState(p.chapters[0].id, shortState.apply(shortState.tr.insertText('More text '.repeat(2000), 1))); emit('doc-changed'); await wait();
      const pageNumbers = [...document.querySelectorAll('.hf-footer')].map(el => el.textContent.match(/Page (\\d+) of (\\d+)/));
      check('page offsets include long preceding chapters', +pageNumbers[0][1] > 2 && pageNumbers[1][1] === pageNumbers[1][2]);
      setChapterState(p.chapters[0].id, shortState); emit('doc-changed');
      const inactive = chapterState(p.chapters[0].id);
      setChapterState(p.chapters[0].id, inactive.apply(inactive.tr.insertText('Replacement ', 1))); emit('doc-changed');
      check('inactive previews reflect book-wide edits', document.querySelector('.chapter-preview').textContent.includes('Replacement First chapter edits'));
      const firstPaper = document.querySelector('.chapter-paper');
      const firstText = firstPaper.querySelector('.chapter-preview p');
      firstText.dispatchEvent(new MouseEvent('mousedown', { bubbles: true, clientX: 600, clientY: 450 }));
      check('single click activates an inactive chapter', app.view === p.chapters[0].id && firstPaper.contains(app.editor.view.dom));
      await new Promise(resolve => setTimeout(resolve, 550));
      app.editor.commands.focus('end'); app.editor.commands.insertContent(' Undo me');
      openView(p.chapters[1].id); openView(p.chapters[0].id); app.editor.commands.undo();
      check('chapter undo survives navigation', !app.editor.getText().includes('Undo me') && app.editor.getText().includes('First chapter edits'));
      check('publishing elements registered', !!app.editor.schema.nodes.pageElement && !!app.editor.schema.nodes.footnote);
      const { runAction } = await import('/src/keybinds.js');
      runAction('table');
      check('table action opens size options', document.querySelector('.modal-overlay h2')?.textContent === 'Insert table');
      applyDialog(); await wait();
      check('table insertion honors dimensions', app.editor.getJSON().content.some(node => node.type === 'table' && node.content.length === 4 && node.content[0].content.length === 3));
      const tableDialog = tableOptionsDialog();
      const color = document.querySelector('.modal-overlay input[type=color]'); color.value = '#ff0000';
      applyDialog(); await tableDialog; await wait();
      check('table appearance exports', buildBookHTML().includes('--table-border: #ff0000') || buildBookHTML().includes('--table-border:#ff0000'));
      check('table appearance updates live', getComputedStyle(app.editor.view.dom.querySelector('table')).getPropertyValue('--table-border').trim() === '#ff0000');
      app.editor.commands.focus('end'); app.editor.commands.insertContent('<p>After the table</p>');
      let dialog = elementDialog('caption');
      document.querySelector('.modal-overlay textarea').value = 'A caption <with> details';
      applyDialog(); await dialog; await wait();
      check('caption insertion and escaping', buildBookHTML().includes('A caption &lt;with&gt; details'));
      app.editor.commands.focus('end');
      dialog = footnoteDialog(); document.querySelector('.modal-overlay textarea').value = 'A source & explanation';
      applyDialog(); await dialog; await wait();
      check('inline footnote and chapter notes', !!document.querySelector('.footnote-reference') && document.querySelector('.chapter-note')?.textContent.includes('A source & explanation'));
      check('footnotes export safely', buildBookHTML().includes('A source &amp; explanation') && buildBookHTML().includes('class="chapter-notes"'));
      app.editor.commands.focus('end');
      dialog = elementDialog('toc'); applyDialog(); await dialog; await wait();
      check('contents include chapter links', document.querySelector('.book-contents a')?.textContent === 'Chapter 1' && buildBookHTML().includes('href="#chapter-'));
      app.project.chapters[1].title = 'Renamed chapter'; emit('chapters-changed');
      check('contents refresh after chapter rename', document.querySelector('.book-contents')?.textContent.includes('Renamed chapter'));
      dialog = watermarkDialog(); document.querySelector('.modal-overlay input').value = 'DRAFT'; applyDialog(); await dialog; await wait();
      check('watermark preview and export', document.querySelector('.chapter-paper').dataset.watermark === 'DRAFT' && buildBookHTML().includes('<span>DRAFT</span>'));
      const before = JSON.stringify(app.project.chapters[0].content);
      addChapter(); moveChapter(app.view, -1);
      check('chapter add and reorder preserve content', app.project.chapters.length === 3 && document.querySelectorAll('.chapter-paper').length === 3 && JSON.stringify(app.project.chapters.find(ch => ch.id === p.chapters[0].id).content) === before);
      const saved = JSON.parse(JSON.stringify(app.project)); loadProject(saved, null); openView(saved.chapters.find(ch => ch.id === p.chapters[0].id).id);
      check('project reload preserves artwork and elements', app.project.titleImages.length === 1 && app.editor.getJSON().content.some(node => node.type === 'pageElement'));
      document.getElementById('chapter-title').value = 'Reloaded chapter'; document.getElementById('chapter-title').dispatchEvent(new Event('input'));
      check('chapter title edits the reloaded project', app.project.chapters.find(ch => ch.id === app.view).title === 'Reloaded chapter');
      const titleInput = document.getElementById('chapter-title'); titleInput.focus();
      titleInput.value += '!'; titleInput.dispatchEvent(new Event('input'));
      check('chapter renaming keeps typing focus', document.activeElement === titleInput);
      const { openTimeMachine, closeTimeMachine } = await import('/src/features/timeMachine.js');
      openTimeMachine();
      check('Time Machine preview remains visible', getComputedStyle(document.getElementById('tm-paper')).display !== 'none');
      openView('title');
      check('Time Machine closes when returning to title', !document.querySelector('.tm-bar') && !document.body.classList.contains('time-machine'));
      openView(saved.chapters.find(ch => ch.id === p.chapters[0].id).id);
      const native = await exportPayload('moopress');
      check('native save retains editable element data', native.json.titleImages.length === 1 && JSON.stringify(native.json).includes('pageElement') && JSON.stringify(native.json).includes('footnote'));
      const textExport = await exportPayload('txt');
      check('plain text export retains captions and note text', textExport.text.includes('A caption <with> details') && textExport.text.includes('A source & explanation'));
      const wordExport = await exportPayload('docx');
      check('Word export retains artwork and publishing text', wordExport.html.includes('<img') && wordExport.html.includes('A caption &lt;with&gt; details') && wordExport.html.includes('A source &amp; explanation'));
      const rtfExport = await exportPayload('rtf');
      check('RTF export retains artwork and publishing text', rtfExport.text.includes('\\\\pict') && rtfExport.text.includes('A caption <with> details') && rtfExport.text.includes('A source & explanation'));
      const odtExport = await exportPayload('odt');
      check('OpenDocument export produces a document', odtExport.bytes.length > 1000);
      check('old books receive safe element defaults', normalizeProject({ chapters: saved.chapters }).titleImages.length === 0 && normalizeProject({ chapters: saved.chapters }).layout.watermark.text === '');
      app.editor.view.dom.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 600, clientY: 400 }));
      document.querySelector('.radial-centre')?.click();
      check('more expands into circular tools', document.querySelectorAll('.radial-outer').length >= 12 && !document.querySelector('.popover'));
      await new Promise(resolve => setTimeout(resolve, 650));
      check('outer icons stay inside the window', [...document.querySelectorAll('.radial-outer')].every(button => { const rect = button.getBoundingClientRect(); return rect.left >= 0 && rect.top >= 0 && rect.right <= innerWidth && rect.bottom <= innerHeight; }));
      document.querySelector('.radial-centre').click();
      check('radial expansion can collapse', document.querySelector('.radial-centre').getAttribute('aria-expanded') === 'false');
      document.querySelector('.radial-centre').click();
      document.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
      check('radial tools support keyboard navigation', document.activeElement.closest('.radial-menu'));
      await new Promise(resolve => setTimeout(resolve, 650));
      window.testExportHTML = buildBookHTML();
      window.testChecks = checks;
      return checks;
    })()`);
    const outputDir = path.join(__dirname, '..', '.test-output');
    await fs.mkdir(outputDir, { recursive: true });
    await fs.writeFile(path.join(outputDir, 'radial.png'), (await win.webContents.capturePage()).toPNG());
    await win.webContents.executeJavaScript(`(async () => { const { closeRadial } = await import('/src/features/radialMenu.js'); closeRadial(); const { openView } = await import('/src/editor.js'); openView('title'); })()`);
    await new Promise(resolve => setTimeout(resolve, 300));
    await fs.writeFile(path.join(outputDir, 'title.png'), (await win.webContents.capturePage()).toPNG());
    const html = await win.webContents.executeJavaScript('window.testExportHTML');
    await fs.writeFile(path.join(outputDir, 'book.html'), html);
    const preview = new BrowserWindow({ show: false, width: 1000, height: 1200, webPreferences: { offscreen: true, backgroundThrottling: false } });
    await preview.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(html));
    await fs.writeFile(path.join(outputDir, 'book.pdf'), await preview.webContents.printToPDF({ printBackground: true, preferCSSPageSize: true }));
    preview.destroy();
    for (const check of result) console.log(`${check.pass ? 'PASS' : 'FAIL'} ${check.name}`);
    app.exit(result.every(check => check.pass) ? 0 : 1);
  } catch (error) { console.error(error); app.exit(1); }
});
